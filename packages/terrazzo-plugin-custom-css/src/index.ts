import type { Plugin } from "@terrazzo/parser";

import buildAll from "./build";
import { CUSTOM_CSS_PLUGIN_NAME } from "./constants";

export interface CustomCssPluginOptions {
  /** Where to output CSS */
  filename?: string;
}

export default function pluginCustomCss(options?: CustomCssPluginOptions): Plugin {
  const filename = options?.filename ?? "index.scss";

  return {
    name: CUSTOM_CSS_PLUGIN_NAME,
    enforce: "post",
    config(config) {
      // plugin-css is required for transforms. throw error
      if (!config.plugins.some((p) => p.name === "@terrazzo/plugin-css")) {
        throw new Error(
          `${CUSTOM_CSS_PLUGIN_NAME} relies on @terrazzo/plugin-css. Please install @terrazzo/plugin-css and follow setup to add to your config.`,
        );
      }
    },

    async build(options) {
      const output = [`/* Generated by ${CUSTOM_CSS_PLUGIN_NAME}. DO NOT EDIT! */`];
      buildAll(output, options);
      options.outputFile(filename, output.join("\n"));
    },
  };
}
