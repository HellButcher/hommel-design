import type { Group, GroupOrToken, Plugin, Token, TokenTransformed } from '@terrazzo/parser';
import { generateShorthand, makeCSSVar } from '@terrazzo/token-tools/css';


const CSS_FORMAT_ID = 'css';
const CUSTOM_CSS_PLUGIN_NAME = '@hommel/terrazzo-plugin-custom-css';

const TOKEN_TYPE_SYNTAX: Record<string, string> = {
  color: '<color>',
  dimension: '<length>',
  duration: '<time>',
  fontWeight: '<integer>',
  number: '<number>',
  boolean: '<integer>',
  fontFamily: '*',
  string: '*',
  cubicBezier: '*',
  border: '*',
  shadow: '*',
  gradient: '*',
  typography: '*',
  transition: '*',
  strokeStyle: '*',
  link: '<url>',
};

const SUB_PROPERTY_SYNTAX: Record<string, Record<string, string>> = {
  border: { color: '<color>', width: '<length>', style: '*' },
  shadow: {
    color: '<color>',
    'offset-x': '<length>',
    'offset-y': '<length>',
    blur: '<length>',
    spread: '<length>',
  },
  transition: { duration: '<time>', delay: '<time>', 'timing-function': '*' },
  typography: {
    'font-family': '*',
    'font-size': '<length>',
    'font-weight': '<integer>',
    'line-height': '*',
    'letter-spacing': '<length>',
    'font-style': '*',
    'font-variant': '*',
    'font-variation-settings': '*',
    'text-decoration': '*',
    'text-transform': '*',
  },
  strokeStyle: { 'dash-array': '*', 'line-cap': '*' },
};

function _generatePropertyDefinitionSingle(
  varName: string,
  cssType: string,
  initialValue?: string,
) {
  const decls = [
    `syntax: '${cssType}'`,
    'inherits: true',
  ];
  if (initialValue) {
    decls.push(`initial-value: ${initialValue}`);
  }
  return `@property ${varName} {\n  ${decls.join(';\n  ')};\n}`;
}

function isComputationallyIndependent(token: TokenTransformed) {
  return !token.token.aliasOf;
}

export function generatePropertyDefinition(
  varName: string,
  token: TokenTransformed,
) {
  const cssSyntax = TOKEN_TYPE_SYNTAX[token.token.$type] ?? '*';
  if (cssSyntax === '*' || !isComputationallyIndependent(token)) {
    return undefined;
  }
  if (token.type === 'SINGLE_VALUE') {
    return _generatePropertyDefinitionSingle(varName, cssSyntax, token.value);
  } else if (token.type === 'MULTI_VALUE') {
    const decls = [];
    for (const [name, subValue] of Object.entries(token.value)) {
      let subVarName = name === '.' ? varName : `${varName}-${name}`;
      const subCssSyntax = SUB_PROPERTY_SYNTAX[token.token.$type]?.[name] ?? '*';
      if (subCssSyntax === '*' || typeof subValue === 'string' && subValue.includes('var(')) {
        continue;
      }
      decls.push(_generatePropertyDefinitionSingle(subVarName, subCssSyntax, subValue));
    }
    if (decls.length > 0) {
      return decls.join('\n');
    } else {
      return undefined;
    }
  }
}

function walkGroups(item: GroupOrToken|GroupOrToken[]|Record<string, GroupOrToken>, callback: (id: string, g: Token) => void, path: string[] = []) {
  if (Array.isArray(item)) {
    for (const g of item) {
      walkGroups(g, callback, path);
    }
    return;
  }
  if ('$value' in item) {
    callback(path.join('.'), item as Token);
  } else {
    for (const key of Object.keys(item)) {
      if (!key.startsWith('$')) {
        path.push(key);
        walkGroups((item as Record<string, GroupOrToken>)[key] as GroupOrToken, callback, path);
        path.pop();
      }
    }
  }
}

export interface CustomCssPluginOptions {
  /** Where to output CSS */
  filename?: string;
}

export default function pluginCustomCss(options?: CustomCssPluginOptions): Plugin {
  const filename = options?.filename ?? 'index.scss';

  return {
    name: CUSTOM_CSS_PLUGIN_NAME,
    enforce: 'post',
    config(config) {
      // plugin-css is required for transforms. throw error
      if (!config.plugins.some((p) => p.name === '@terrazzo/plugin-css')) {
        throw new Error(`${CUSTOM_CSS_PLUGIN_NAME} relies on @terrazzo/plugin-css. Please install @terrazzo/plugin-css and follow setup to add to your config.`);
      }
    },

    async build({ getTransforms, outputFile, resolver }) {
      const output = [`/* Generated by ${CUSTOM_CSS_PLUGIN_NAME}. DO NOT EDIT! */`];

      const defaultTokensById: Record<string, TokenTransformed> = {};
      for (const token of getTransforms({ format: CSS_FORMAT_ID })) {
        const localID = token.localID;
        if (!localID) {
          continue;
        }
        defaultTokensById[token.id] = token;
        var prop = generatePropertyDefinition(localID, token);
        if (prop) {
          output.push(prop);
        }
      }

      function generateToken(token: TokenTransformed) {
        if (!token) return;
        if (token.type === 'SINGLE_VALUE') {
          output.push(`  ${token.localID}: ${token.value};`);
        } else if (token.type === 'MULTI_VALUE') {
          for (const [name, subValue] of Object.entries(token.value)) {
            output.push(`  ${token.localID}-${name}: ${subValue};`);
          }
          const shorthand = generateShorthand({
            token: { ...token.token, $value: token.value as any },
            localID: token.localID!,
            omitTypographyShorthand: false,
          });
          if (shorthand) {
            output.push(`  ${token.localID}: ${shorthand};`);
          }
        }
      }
      

      for (const item of resolver.source.resolutionOrder) {
        switch (item.type) {
          case 'set':
            output.push(`/** set=${item.name} */`);
            output.push(':root {');
            walkGroups(item.sources, (id, g) => {
              const token = defaultTokensById[id];
              if (token) {
                generateToken(token);
              }
            });
            output.push('}');
            break;
          case 'modifier':
            output.push(`/** modifier=${item.name} */`);
            for (const context of Object.keys(item.contexts)) {
              output.push(`/**  modifier=${item.name} context=${context} */`);
              const isDefault = context === item.default;
              const contextTokens = getTransforms({ format: CSS_FORMAT_ID, input: { [item.name]: context} })
              const contextTokensById: Record<string, TokenTransformed> = {};
              for (const token of contextTokens) {
                if (token.localID) {
                  contextTokensById[token.id] = token;
                }
              }
              output.push(`${isDefault ? ':root, ' : ''}[data-${item.name}="${context}"] {`);
                walkGroups(item.contexts[context], (id, g) => {
                  const token = contextTokensById[id];
                  if (token) {
                    generateToken(token);
                  }
                });
              output.push('}');
            }
            break;
        }
      }
      outputFile(filename, output.join('\n'));
    }
  };
}

