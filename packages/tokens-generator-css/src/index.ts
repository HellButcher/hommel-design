import {
  type Plugin,
  type Token,
  type TokenDocument,
  type TokenMap,
  type TypographyValue,
} from "@hommel/tokens-generator";

import { propertyRules } from "./property.ts";
import { kebabCase, toCss, TYPOGRAPHY_KEYS, typographyProperties, type VarName } from "./values.ts";

export const PLUGIN_NAME = "@hommel/tokens-generator-css";

export interface CssPluginOptions {
  /** output file, defaults to `index.css` */
  filename?: string;
  /** prefix of the custom property names (`--{prefix}-...`) */
  prefix?: string;
  /** modifier -> context -> media query that also activates the (non-default) context */
  mediaQueries?: Record<string, Record<string, string>>;
}

export default function css(options: CssPluginOptions = {}): Plugin {
  const filename = options.filename ?? "index.css";
  const prefix = options.prefix ? `--${options.prefix}-` : "--";
  const varName: VarName = (id) => prefix + id.split(".").map(kebabCase).join("-");

  /** declarations for a token: typography gets one declaration per property plus the `font` shorthand */
  function declarations(token: Token): [name: string, value: string][] {
    const name = varName(token.id);
    if (token.type !== "typography") {
      return [[name, toCss(token, varName)]];
    }
    const subVarName = (key: keyof TypographyValue) => varName(`${token.id}.${key}`);
    const props = typographyProperties(token.value, varName);
    return [
      ...TYPOGRAPHY_KEYS.map((key): [string, string] => [subVarName(key), props[key]]),
      [
        name,
        `var(${subVarName("fontWeight")}) var(${subVarName("fontSize")})/var(${subVarName("lineHeight")}) var(${subVarName("fontFamily")})`,
      ],
    ];
  }

  function block(tokens: TokenMap): string[] {
    return [...tokens.values()].flatMap((token) =>
      declarations(token).map(([name, value]) => `  ${name}: ${value};`),
    );
  }

  function generate(document: TokenDocument): string {
    const output = [`/* Generated by ${PLUGIN_NAME}. DO NOT EDIT! */`];
    for (const token of document.defaultTokens.values()) {
      output.push(...propertyRules(token, varName));
    }

    // later sets are re-declared below modifier attributes so their var() references re-evaluate
    const rootSelectors = [":root"];
    for (const item of document.resolutionOrder) {
      if (item.type === "set") {
        output.push(`/** set=${item.name} */`, `${rootSelectors.join(", ")} {`);
        output.push(...block(item.tokens), "}");
        continue;
      }
      output.push(`/** modifier=${item.name} */`);
      for (const [context, tokens] of Object.entries(item.contexts)) {
        output.push(`/**  modifier=${item.name} context=${context} */`);
        const isDefault = context === document.defaultInput[item.name];
        const body = block(tokens);
        const mediaQuery = !isDefault && options.mediaQueries?.[item.name]?.[context];
        if (mediaQuery) {
          output.push(`@media ${mediaQuery} { :root {`, ...body, "}}");
        }
        const selector = `[data-${item.name}=${JSON.stringify(context)}]`;
        output.push(`${isDefault ? ":root, " : ""}${selector} {`, ...body, "}");
      }
      const modifierSelector = `[data-${item.name}]`;
      if (!rootSelectors.includes(modifierSelector)) rootSelectors.push(modifierSelector);
    }
    return output.join("\n") + "\n";
  }

  return {
    name: PLUGIN_NAME,
    build({ document, outputFile }) {
      outputFile(filename, generate(document));
    },
  };
}
